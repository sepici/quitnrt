HEIGHT = 9


def _glyph(ch):
    if ch in _LOWER:
        rows = _LOWER[ch].split('|')
    elif ch in _UPPER:
        rows = _UPPER[ch].split('|') + ['.' * len(_UPPER[ch].split('|')[0])] * 2
    else:
        raise KeyError(f"No glyph for {ch!r}")
    return rows


def text_width(s, scale=1):
    if not s:
        return 0
    return (sum(len(_glyph(c)[0]) + 1 for c in s) - 1) * scale


class Image:
    """An RGB canvas with just what the preview sheets need."""

    def __init__(self, w, h, bg):
        self.w, self.h = w, h
        self.px = bytearray(bytes(bg) * (w * h))

    def rect(self, x, y, w, h, rgb):
        x0, y0, x1, y1 = max(0, x), max(0, y), min(self.w, x + w), min(self.h, y + h)
        if x1 <= x0 or y1 <= y0:
            return
        row = bytes(rgb) * (x1 - x0)
        for yy in range(y0, y1):
            i = (yy * self.w + x0) * 3
            self.px[i:i + len(row)] = row

    def frame(self, x, y, w, h, rgb, t=1):
        self.rect(x, y, w, t, rgb)
        self.rect(x, y + h - t, w, t, rgb)
        self.rect(x, y, t, h, rgb)
        self.rect(x + w - t, y, t, h, rgb)

    def text(self, x, y, s, rgb, scale=1):
        for c in s:
            rows = _glyph(c)
            for gy, row in enumerate(rows):
                for gx, on in enumerate(row):
                    if on == '#':
                        self.rect(x + gx * scale, y + gy * scale, scale, scale, rgb)
            x += (len(rows[0]) + 1) * scale

    def save(self, path):
        raw = bytearray()
        stride = self.w * 3
        for y in range(self.h):
            raw.append(0)
            raw += self.px[y * stride:(y + 1) * stride]

        def chunk(tag, data):
            return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xFFFFFFFF)

        png = (b'\x89PNG\r\n\x1a\n'
               + chunk(b'IHDR', struct.pack('>IIBBBBB', self.w, self.h, 8, 2, 0, 0, 0))
               + chunk(b'IDAT', zlib.compress(bytes(raw), 9))
               + chunk(b'IEND', b''))
        with open(path, 'wb') as f:
            f.write(png)
